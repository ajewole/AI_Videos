"""Generates the voiceover from script.json and the timeline the scene and music follow.

Each VO line is spoken with Piper (offline neural TTS, public-domain LibriVox voice), then the
lines are laid end to end: a scene starts with `lead` seconds of air, lines are separated by GAP,
and the scene ends `tail` seconds after its last line. Writes:
  voice.wav     the full narration (48 kHz mono)
  timeline.js   window.TIMELINE = scenes with start/end/line times, loaded by scene.html
  timeline.json the same data for music.py
Usage: python3 voiceover.py
"""
import json
import subprocess
import sys
import urllib.request
import wave
from pathlib import Path

import numpy as np

HERE = Path(__file__).resolve().parent
CACHE = HERE / '.cache'
SR = 48000
GAP = 0.25          # silence between lines inside a scene
LEAD = 0.35         # default air before the first line of a scene
TAIL = 0.55         # default air after the last line of a scene
VOICES = 'https://huggingface.co/rhasspy/piper-voices/resolve/main/en/'

script = json.loads((HERE / 'script.json').read_text())
voice = script['voice']


def model_path():
    lang, name, quality = voice.split('-')
    CACHE.mkdir(exist_ok=True)
    for ext in ('.onnx', '.onnx.json'):
        dest = CACHE / (voice + ext)
        if not dest.exists():
            url = f'{VOICES}{lang}/{name}/{quality}/{voice}{ext}'
            print('downloading', url)
            urllib.request.urlretrieve(url, dest)
    return CACHE / (voice + '.onnx')


def speak(text, model, idx):
    out = CACHE / f'line{idx:02d}.wav'
    subprocess.run([sys.executable, '-m', 'piper', '-m', str(model), '-f', str(out),
                    '--length-scale', str(script.get('length_scale', 1.0)), '--sentence-silence', '0.18'],
                   input=text.encode(), check=True, capture_output=True)
    with wave.open(str(out)) as w:
        sr = w.getframerate()
        x = np.frombuffer(w.readframes(w.getnframes()), '<i2').astype(float) / 32768
    # resample to 48 kHz and trim leading/trailing silence
    x = np.interp(np.arange(int(len(x) * SR / sr)) * sr / SR, np.arange(len(x)), x)
    loud = np.flatnonzero(np.abs(x) > 0.01)
    return x[max(loud[0] - 400, 0): loud[-1] + 2400]


def resumes(x, min_gap=0.14):
    """Offsets (s) where speech resumes after a pause inside a line: used to time text reveals."""
    win = int(SR * 0.01)
    quiet = np.abs(x[: len(x) // win * win]).reshape(-1, win).max(axis=1) < 0.012
    out, run = [], 0
    for i, q in enumerate(quiet):
        if q:
            run += 1
        else:
            if run * 0.01 >= min_gap:
                out.append(round(i * 0.01, 3))
            run = 0
    return out


model = model_path()
clips, t, idx = [], 0.0, 0
for scene in script['scenes']:
    scene['start'] = round(t, 3)
    t += scene.get('lead', LEAD)
    scene['lines_t'] = []
    scene['resumes'] = []
    for k, text in enumerate(scene['vo']):
        if k:
            t += scene.get('gap', GAP)
        x = speak(text, model, idx)
        idx += 1
        clips.append((t, x))
        scene['lines_t'].append([round(t, 3), round(t + len(x) / SR, 3)])
        scene['resumes'].append([round(t + r, 3) for r in resumes(x)])
        t += len(x) / SR
    t += scene.get('tail', TAIL)
    scene['end'] = round(t, 3)
    print(f"{scene['id']:>6}  {scene['start']:6.2f} - {scene['end']:6.2f}")

duration = round(t, 3)
audio = np.zeros(int(duration * SR) + 1)
for start, x in clips:
    i = int(start * SR)
    audio[i:i + len(x)] += x
audio *= 0.9 / np.max(np.abs(audio))
with wave.open(str(HERE / 'voice.wav'), 'wb') as w:
    w.setnchannels(1)
    w.setsampwidth(2)
    w.setframerate(SR)
    w.writeframes((audio * 32767).astype('<i2').tobytes())

timeline = {'duration': duration, 'heart': script['heart'], 'scenes': script['scenes']}
(HERE / 'timeline.json').write_text(json.dumps(timeline, indent=1, ensure_ascii=False))
(HERE / 'timeline.js').write_text('// generated by voiceover.py from script.json\nwindow.TIMELINE = '
                                   + json.dumps(timeline, indent=1, ensure_ascii=False) + ';\n')
print(f'wrote voice.wav, timeline.js ({duration:.1f}s)')
